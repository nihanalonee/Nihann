function mulberry32(seed: number) {
  return function () {
    let t = (seed += 0x6d2b79f5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function history(seed: number, end: number, points = 64, drift = 0.12, wave = 0.16) {
  const rng = mulberry32(seed);
  const values: number[] = [];
  let value = end * (0.72 + rng() * 0.08);
  for (let i = 0; i < points; i += 1) {
    const pull = ((end - value) / end) * 0.09;
    const noise = (rng() - 0.5) * wave * 0.02;
    value = Math.max(end * 0.4, value * (1 + drift * 0.006 + Math.sin(i / 5.5) * 0.002 + noise + pull));
    values.push(value);
  }
  values[values.length - 1] = end;
  return values.map((v) => Math.round(v * 100) / 100);
}

