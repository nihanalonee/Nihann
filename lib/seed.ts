function mulberry32(seed: number) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

function history(price: number, volatility: number, seed: number, points = 64): number[] {
  const rand = mulberry32(seed)
  const out: number[] = []
  let value = price * (0.72 + rand() * 0.2)
  for (let i = 0; i < points; i += 1) {
    const drift = (price - value) * 0.035
    const noise = value * volatility * (rand() - 0.48) * 0.34
    value = Math.max(price * 0.08, value + drift + noise)
    out.push(Number(value.toFixed(value < 1 ? 6 : 2)))
  }
  out[out.length - 1] = price
  return out
}

function indexHistory(seed: number, points = 72): number[] {
  const rand = mulberry32(seed)
  const out: number[] = []
  let value = 3910
  for (let i = 0; i < points; i += 1) {
    value += 4.2 + (rand() - 0.47) * 42
    out.push(Number(value.toFixed(2)))
  }
  out[out.length - 1] = 4286.42
  return out
}

